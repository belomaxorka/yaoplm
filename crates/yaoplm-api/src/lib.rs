//! Transport-agnostic RPC layer shared by the desktop app, the CLI and the
//! server (ARCHITECTURE.md §4).
//!
//! Every operation is a [`Request`] variant. [`Api::dispatch`] answers it with
//! a [`Response`] or an [`ApiError`]. Long-running operations return a
//! [`JobId`] and report progress as [`JobEvent`]s through [`Api::subscribe`];
//! `GetJob` returns the result.
//!
//! Writes follow plan → confirm → execute (SPEC §6): `PlanImport`,
//! `RenameGame`, `DeleteGame`, `MoveGame`, `ConvertGames`, `WriteCfg`,
//! `CreateVmc`, `PlanInit` and `PlanRecovery` only plan and return a
//! [`plans::PlanView`]; `ExecutePlan` runs it.
//!
//! The wire format is JSON tagged by `type`, e.g. `{"type":"Ping"}`.
//! TypeScript types for `web/` are generated by ts-rs:
//! `cargo test -p yaoplm-api --features ts-export`.

