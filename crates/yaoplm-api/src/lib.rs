pub const NAME: &str = "YAOPLM";
pub const VERSION: &str = env!("CARGO_PKG_VERSION");

/// Shared entry point of every front end. Synchronous: async transports call
/// [`Api::dispatch`] from a blocking task.
#[derive(Debug)]
pub struct Api {
    events: EventBus,
    paths: PathPolicy,
    jobs: JobManager,
    plans: PlanStore,
    net: Arc<Net>,
}

impl Default for Api {
    fn default() -> Self {
        Self::with_policy(PathPolicy::Any)
    }
}

pub(crate) fn op_error(err: OpError) -> ApiError {
    match err {
        OpError::NotFound(m) => ApiError::not_found(m),
        OpError::Invalid(m) | OpError::Conflict(m) => ApiError::bad_request(m),
        OpError::Io(e) => ApiError::internal(e.to_string()),
    }
}

fn io_error(err: std::io::Error) -> ApiError {
    ApiError::internal(err.to_string())
}

fn name_style(style: Option<protocol::NameStyle>) -> Option<iso_name::NameStyle> {
    style.map(|s| match s {
        NameStyle::IdTitle => iso_name::NameStyle::WithStartup,
        NameStyle::Title => iso_name::NameStyle::TitleOnly,
    })
}

impl Api {
    /// Any path may be opened: the desktop app and the CLI.
    pub fn new() -> Self {
        Self::default()
    }

    /// Only paths inside `roots` (canonical) may be opened: the server.
    pub fn with_roots(roots: Vec<PathBuf>) -> Self {
        Self::with_policy(PathPolicy::Within(roots))
    }

    fn with_policy(paths: PathPolicy) -> Self {
        let events = EventBus::default();
        Self {
            jobs: JobManager::new(events.clone()),
            events,
            paths,
            plans: PlanStore::default(),
            net: Arc::new(Net::new(art::default_data_dir())),
        }
    }

    /// Keeps the art cache and other app data in `dir` instead of the
    /// platform's app data folder (ARCHITECTURE.md §6).
    pub fn with_data_dir(mut self, dir: impl Into<PathBuf>) -> Self {
        self.net = Arc::new(Net::new(dir.into()));
        self
    }

    pub fn data_dir(&self) -> &Path {
        self.net.data_dir()
    }

    pub fn jobs(&self) -> &JobManager {
        &self.jobs
    }

    fn root(&self, raw: &str) -> Result<(PathBuf, HostFs), ApiError> {
        let path = self.paths.resolve(raw)?;
        if !path.is_dir() {
            return Err(ApiError::bad_request(format!(
                "{} is not a folder",
                display_path(&path)
            )));
        }
        let fs = HostFs::new(&path).map_err(io_error)?;
        Ok((path, fs))
    }

    fn game_ref(&self, root: &Path, game: GameRef) -> Result<ops::GameRef, ApiError> {
        match game {
            GameRef::Image { path } => {
                let candidate = Path::new(&path);
                let relative = if candidate.is_absolute() {
                    let resolved = self.paths.resolve(&path)?;
                    resolved
                        .strip_prefix(root)
                        .map_err(|_| {
                            ApiError::bad_request(format!("{path} is not on this device"))
                        })?
                        .to_path_buf()
                } else {
                    candidate.to_path_buf()
                };
                let text: Vec<String> = relative
                    .components()
                    .map(|c| c.as_os_str().to_string_lossy().into_owned())
                    .collect();
                let rel = RelPath::new(&text.join("/"))
                    .map_err(|e| ApiError::bad_request(e.to_string()))?;
                Ok(ops::GameRef::Image { path: rel })
            }
            GameRef::Ul {
                index,
                startup,
                name,
            } => Ok(ops::GameRef::Ul {
                index: index as usize,
                startup,
                name,
            }),
        }
    }

    fn store(&self, root: PathBuf, plan: Plan) -> Response {
        Response::Plan(Box::new(self.plans.insert(root, plan)))
    }

    pub fn dispatch(&self, request: Request) -> Result<Response, ApiError> {
        match request {
            Request::Ping => Ok(Response::Pong),
            Request::Version => Ok(Response::Version {
                name: NAME.to_owned(),
                version: VERSION.to_owned(),
            }),
            Request::ListDevices { profile } => {
                let options = DiagnoseOptions {
                    profile: profile.unwrap_or_default().into(),
                    boot_from_device: false,
                };
                let devices = match &self.paths {
                    PathPolicy::Any => yaoplm_device::list_volumes()
                        .iter()
                        .map(|v| DeviceInfo::new(v, &options))
                        .collect(),
                    // A server shows its library roots, never the host's disks.
                    PathPolicy::Within(roots) => roots
                        .iter()
                        .filter_map(|root| {
                            let volume = yaoplm_device::volume_for_path(root).ok()?;
                            let mut info = DeviceInfo::new(&volume, &options);
                            info.root = display_path(root);
                            Some(info)
                        })
                        .collect(),
                };
                Ok(Response::Devices { devices })
            }
            Request::InspectDevice {
                root,
                profile,
                boot_from_device,
            } => {
                let (path, fs) = self.root(&root)?;
                let volume = yaoplm_device::volume_for_path(&path).map_err(io_error)?;
                let options = DiagnoseOptions {
                    profile: profile.unwrap_or_default().into(),
                    boot_from_device: boot_from_device.unwrap_or(false),
                };
                let mut info = DeviceInfo::new(&volume, &options);
                info.root = display_path(&path);
                info.add_apple_double(count_apple_double(&path));
                let (journals, unreadable) =
                    yaoplm_core::journal::load_all(&fs).map_err(io_error)?;
                info.unfinished = journals
                    .into_iter()
                    .map(|j| j.id)
                    .chain(unreadable.into_iter().map(|u| u.file))
                    .collect();
                Ok(Response::Device(Box::new(info)))
            }
            Request::ScanLibrary {
                root,
                profile,
                verify,
            } => {
                let path = self.paths.resolve(&root)?;
                let profile = profile.unwrap_or_default();
                let options = yaoplm_core::ScanOptions {
                    profile: profile.into(),
                    verify_images: verify.unwrap_or(true),
                };
                let title = format!("Scan {}", display_path(&path));
                let root = display_path(&path);
                let net = Arc::clone(&self.net);
                let job = self.jobs.spawn(
                    JobKind::ScanLibrary,
                    title,
                    Some(root),
                    Queue::Read,
                    move |ctx| {
                        let library =
                            yaoplm_core::scan_library_with(&path, &options, &mut |done, total| {
                                ctx.progress(done, Some(total), None);
                                !ctx.is_cancelled()
                            })
                            .map_err(|err| match err {
                                yaoplm_core::ScanError::NotADirectory(_) => {
                                    ApiError::bad_request(err.to_string())
                                }
                                yaoplm_core::ScanError::Cancelled => {
                                    ApiError::new(ErrorCode::Cancelled, "cancelled")
                                }
                                yaoplm_core::ScanError::Io { .. } => {
                                    ApiError::internal(err.to_string())
                                }
                            })?;
                        let mut wire = Library::from_core(&library, profile);
                        verify::attach_checks(&mut wire, &library, &net);
                        Ok(JobResult::Library(Box::new(wire)))
                    },
                );
                Ok(Response::Job { job })
            }
            Request::ImageInfo { path, profile } => {
                let path = self.paths.resolve(&path)?;
                if path.is_dir() {
                    return Err(ApiError::bad_request(format!(
                        "{} is a folder",
                        display_path(&path)
                    )));
                }
                let profile: LoaderProfile = profile.unwrap_or_default();
                let info = yaoplm_core::image_info(&path, profile.into())
                    .map_err(|err| ApiError::bad_request(err.to_string()))?;
                Ok(Response::ImageInfo(Box::new(ImageDetails::from(&info))))
            }
            Request::ListDir { path } => {
                let listing = match path {
                    None => dir::list_top(&self.paths),
                    Some(path) => dir::list_dir(&self.paths, &path)?,
                };
                Ok(Response::Dir(Box::new(listing)))
            }
            Request::PlanInit { root } => {
                let (path, fs) = self.root(&root)?;
                let plan = ops::plan_init(&fs).map_err(io_error)?;
                Ok(self.store(path, plan))
            }
            Request::PlanImport {
                root,
                sources,
                profile,
                name_style: style,
                transfer,
                layout,
                overrides,
                compress,
            } => {
                let (path, fs) = self.root(&root)?;
                // Sources are read, and deleted in move mode: the same
                // allow-list applies to them.
                let inputs = sources
                    .iter()
                    .map(|s| self.paths.resolve(s))
                    .collect::<Result<Vec<_>, _>>()?;
                let overrides = overrides
                    .unwrap_or_default()
                    .into_iter()
                    .map(|o| {
                        Ok(import::ImportOverride {
                            path: self.paths.resolve(&o.source)?,
                            title: o.title,
                            media: o.media.map(Into::into),
                        })
                    })
                    .collect::<Result<Vec<_>, ApiError>>()?;
                let options = ImportOptions {
                    profile: profile.unwrap_or_default().into(),
                    name_style: name_style(style).unwrap_or_default(),
                    transfer: match transfer.unwrap_or_default() {
                        Transfer::Copy => import::Transfer::Copy,
                        Transfer::Move => import::Transfer::Move,
                    },
                    layout: match layout.unwrap_or_default() {
                        Layout::Auto => import::Layout::Auto,
                        Layout::Ul => import::Layout::Ul,
                    },
                    overrides,
                    compress: compress.unwrap_or(false),
                };
                let sources = ArchiveSources::new(&HostSources);
                let plan =
                    import::plan_import(&fs, &sources, &inputs, &options).map_err(io_error)?;
                Ok(self.store(path, plan))
            }
            Request::ConvertGames {
                root,
                games,
                target,
                profile,
                name_style: style,
            } => {
                let (path, fs) = self.root(&root)?;
                let games = games
                    .into_iter()
                    .map(|g| self.game_ref(&path, g))
                    .collect::<Result<Vec<_>, _>>()?;
                let target = match target {
                    ConvertTarget::Iso => convert::Target::Iso,
                    ConvertTarget::Zso => convert::Target::Zso,
                    ConvertTarget::Ul => convert::Target::Ul,
                };
                let options = convert::ConvertOptions {
                    profile: profile.unwrap_or_default().into(),
                    name_style: name_style(style),
                };
                let plan =
                    convert::plan_convert(&fs, &games, target, &options).map_err(op_error)?;
                Ok(self.store(path, plan))
            }
            Request::RenameGame {
                root,
                game,
                title,
                startup,
                name_style: style,
            } => {
                let (path, fs) = self.root(&root)?;
                let game = self.game_ref(&path, game)?;
                let options = RenameOptions {
                    title,
                    startup,
                    name_style: name_style(style),
                };
                let plan = ops::plan_rename(&fs, &game, &options).map_err(op_error)?;
                Ok(self.store(path, plan))
            }
            Request::DeleteGame {
                root,
                game,
                related,
            } => {
                let (path, fs) = self.root(&root)?;
                let game = self.game_ref(&path, game)?;
                let options = DeleteOptions {
                    related: related.unwrap_or(false),
                };
                let plan = ops::plan_delete(&fs, &game, &options).map_err(op_error)?;
                Ok(self.store(path, plan))
            }
            Request::MoveGame { root, game, media } => {
                let (path, fs) = self.root(&root)?;
                let game = self.game_ref(&path, game)?;
                let plan = ops::plan_move(&fs, &game, media.into()).map_err(op_error)?;
                Ok(self.store(path, plan))
            }
            Request::PlanRecovery { root, action } => {
                let (path, fs) = self.root(&root)?;
                let action = match action.unwrap_or_default() {
                    RecoveryAction::Rollback => recovery::RecoveryAction::Rollback,
                    RecoveryAction::Resume => recovery::RecoveryAction::Resume,
                };
                let plan = recovery::plan_recovery(&fs, action).map_err(io_error)?;
                Ok(self.store(path, plan))
            }
            Request::ExecutePlan {
                plan,
                confirm_delete,
            } => {
                let stored = self.plans.take(&plan, |stored| {
                    if let Some(blocker) = stored.plan.blockers().next() {
                        return Err(ApiError::bad_request(blocker.message.clone()));
                    }
                    if stored.plan.transactions.is_empty() {
                        return Err(ApiError::bad_request("the plan has nothing to do"));
                    }
                    if stored.plan.deletes_user_data() && confirm_delete != Some(true) {
                        return Err(ApiError::bad_request(
                            "this plan deletes files; confirm with confirmDelete",
                        ));
                    }
                    Ok(())
                })?;
                let title = stored.plan.title.clone();
                let root = display_path(&stored.root);
                let job = self.jobs.spawn(
                    JobKind::ExecutePlan,
                    title,
                    Some(root),
                    Queue::Write,
                    move |ctx| {
                        let fs = HostFs::new(&stored.root).map_err(io_error)?;
                        let sources = ArchiveSources::new(&HostSources);
                        let plan = &stored.plan;
                        let report = exec::execute_with_events(
                            plan,
                            &Context {
                                fs: &fs,
                                sources: &sources,
                                cancel: ctx.cancel_token(),
                            },
                            &mut |event| match event {
                                Event::Progress(p) => {
                                    ctx.progress(p.done, Some(p.total), Some(&p.title));
                                }
                                Event::Transaction {
                                    index,
                                    title,
                                    state,
                                } => ctx.log(JobLogEntry::Transaction {
                                    at: now_ms(),
                                    index: u32::try_from(index).unwrap_or(u32::MAX),
                                    title: title.to_owned(),
                                    state: match state {
                                        TxEvent::Started => TxLogState::Started,
                                        TxEvent::Done => TxLogState::Done,
                                        TxEvent::RolledBack => TxLogState::RolledBack,
                                        TxEvent::Interrupted => TxLogState::Interrupted,
                                    },
                                }),
                                Event::Step {
                                    transaction,
                                    index,
                                    step,
                                    state,
                                } => {
                                    let view = plans::step(plan, step);
                                    let (state, error) = match state {
                                        StepEvent::Started => (StepLogState::Started, None),
                                        StepEvent::Done => (StepLogState::Done, None),
                                        StepEvent::Undone => (StepLogState::Undone, None),
                                        StepEvent::Failed(error) => {
                                            (StepLogState::Failed, Some(error))
                                        }
                                    };
                                    ctx.log(JobLogEntry::Step {
                                        at: now_ms(),
                                        transaction: u32::try_from(transaction).unwrap_or(u32::MAX),
                                        index: u32::try_from(index).unwrap_or(u32::MAX),
                                        op: view.op,
                                        path: view.path,
                                        to: view.to,
                                        state,
                                        error,
                                    });
                                }
                            },
                        );
                        Ok(JobResult::Execution(ExecutionReport {
                            outcomes: report
                                .outcomes
                                .iter()
                                .map(|o| match o {
                                    Outcome::Done => TxOutcome::Done,
                                    Outcome::RolledBack => TxOutcome::RolledBack,
                                    Outcome::NotStarted => TxOutcome::NotStarted,
                                    Outcome::Interrupted => TxOutcome::Interrupted,
                                })
                                .collect(),
                            cancelled: report.cancelled,
                            error: report.error.as_ref().map(ToString::to_string),
                            journal: report.journal,
                        }))
                    },
                );
                Ok(Response::Job { job })
            }
            Request::DiscardPlan { plan } => {
                if self.plans.discard(&plan) {
                    Ok(Response::Ack)
                } else {
                    Err(ApiError::not_found(format!("no plan {plan}")))
                }
            }
            Request::GetJob { job } => self
                .jobs
                .get(job)
                .map(|info| Response::JobState(Box::new(info)))
                .ok_or_else(|| ApiError::not_found(format!("no job {}", job.0))),
            Request::ListJobs => Ok(Response::Jobs {
                jobs: self.jobs.list(),
            }),
            Request::CancelJob { job } => self.jobs.cancel(job).map(|()| Response::Ack),
            Request::FetchArt {
                root,
                profile,
                scope,
                games,
                sources,
                kind,
            } => {
                let (path, _fs) = self.root(&root)?;
                let kind = art::art_kind(kind.as_deref())?;
                let sources = art::source_configs(&self.paths, &sources.unwrap_or_default())?;
                let params = art::FetchParams {
                    root: path.clone(),
                    profile: profile.unwrap_or_default(),
                    scope: scope.unwrap_or_default(),
                    games,
                    sources,
                    kind,
                };
                let net = Arc::clone(&self.net);
                let plans = self.plans.clone();
                let title = match params.scope {
                    art::ArtScope::Missing => "Find missing covers",
                    art::ArtScope::All => "Find covers for every game",
                };
                let job = self.jobs.spawn(
                    JobKind::FetchArt,
                    title,
                    Some(display_path(&path)),
                    Queue::Read,
                    move |ctx| art::fetch_job(ctx, &net, &plans, params),
                );
                Ok(Response::Job { job })
            }
            Request::SetArt {
                root,
                startup,
                input,
                profile,
                kind,
                overwrite,
            } => {
                let (path, _fs) = self.root(&root)?;
                let kind = art::art_kind(kind.as_deref())?;
                let params = art::SetParams {
                    root: path.clone(),
                    startup,
                    kind,
                    profile: profile.unwrap_or_default(),
                    input,
                    overwrite: overwrite.unwrap_or(true),
                };
                let plan = art::set_art(&self.net, &self.paths, &params)?;
                Ok(self.store(path, plan))
            }
            Request::DeleteArt {
                root,
                startup,
                kind,
            } => {
                let (path, _fs) = self.root(&root)?;
                let kind = art::art_kind(kind.as_deref())?;
                let plan = art::delete_art(&path, &startup, kind)?;
                Ok(self.store(path, plan))
            }
            Request::VerifyGames {
                root,
                games,
                profile,
                md5,
                fresh,
            } => {
                let (path, _fs) = self.root(&root)?;
                let params = verify::VerifyParams {
                    games: games.map(|list| verify::wanted_list(&path, &list)),
                    root: path.clone(),
                    profile: profile.unwrap_or_default(),
                    md5: md5.unwrap_or(false),
                    fresh: fresh.unwrap_or(false),
                };
                let net = Arc::clone(&self.net);
                let job = self.jobs.spawn(
                    JobKind::VerifyGames,
                    "Verify games against Redump",
                    Some(display_path(&path)),
                    Queue::Read,
                    move |ctx| verify::verify_job(ctx, &net, params),
                );
                Ok(Response::Job { job })
            }
            Request::RedumpStatus => Ok(Response::Redump {
                dat: self.net.redump_info().map(Box::new),
            }),
            Request::UpdateRedump { file } => {
                let file = file.map(|f| self.paths.resolve(&f)).transpose()?;
                let title = if file.is_some() {
                    "Import a Redump DAT"
                } else {
                    "Update the Redump DAT"
                };
                let net = Arc::clone(&self.net);
                let job =
                    self.jobs
                        .spawn(JobKind::UpdateRedump, title, None, Queue::Read, move |_| {
                            verify::update_job(&net, file)
                        });
                Ok(Response::Job { job })
            }
            Request::Attribution => Ok(Response::Attribution(Box::new(art::attribution()?))),
            Request::ArtCache => Ok(Response::ArtCache(self.net.cache_info()?)),
            Request::ClearArtCache => self.net.clear_cache().map(|()| Response::Ack),
        }
    }

    /// Parses a JSON request and dispatches it.
    pub fn dispatch_json(&self, json: &str) -> Result<Response, ApiError> {
        let request = serde_json::from_str(json)
            .map_err(|err| ApiError::bad_request(format!("invalid request: {err}")))?;
        self.dispatch(request)
    }

    pub fn events(&self) -> &EventBus {
        &self.events
    }

    pub fn subscribe(&self, listener: impl Fn(&JobEvent) + Send + Sync + 'static) -> Subscription {
        self.events.subscribe(listener)
    }
}

#[cfg(test)]
mod tests {
    use serde_json::json;

    use super::*;

    #[test]
    fn ping_answers_pong() {
        let api = Api::new();
        assert_eq!(api.dispatch(Request::Ping), Ok(Response::Pong));
    }

    #[test]
    fn version_reports_crate_version() {
        let api = Api::new();
        let Ok(Response::Version { name, version }) = api.dispatch(Request::Version) else {
            panic!("expected a Version response");
        };
        assert_eq!(name, "YAOPLM");
        assert_eq!(version, env!("CARGO_PKG_VERSION"));
    }

    #[test]
    fn wire_format_is_tagged_by_type() {
        let api = Api::new();
        let response = api.dispatch_json(r#"{"type":"Ping"}"#).unwrap();
        assert_eq!(
            serde_json::to_value(response).unwrap(),
            json!({"type": "Pong"})
        );

        let event = JobEvent::Progress {
            job: JobId(7),
            done: 5_000_000_000,
            total: None,
            rate: Some(20_000_000),
            item: None,
        };
        assert_eq!(
            serde_json::to_value(event).unwrap(),
            json!({"type": "Progress", "job": 7, "done": 5_000_000_000u64, "total": null, "rate": 20_000_000, "item": null})
        );
        // Field names are camelCase on the wire.
        let request: Request = serde_json::from_value(
            json!({"type": "ExecutePlan", "plan": "p", "confirmDelete": true}),
        )
        .unwrap();
        assert_eq!(
            request,
            Request::ExecutePlan {
                plan: "p".into(),
                confirm_delete: Some(true)
            }
        );
    }

    #[test]
    fn malformed_json_is_bad_request() {
        let api = Api::new();
        for input in ["", "{", r#"{"type":"Nope"}"#, r#"{"kind":"Ping"}"#] {
            let err = api.dispatch_json(input).unwrap_err();
            assert_eq!(err.code, ErrorCode::BadRequest, "input: {input:?}");
        }
    }
}
